export const AGENT_IDS = Object.keys(ADAPTERS);
export const ALIASES = { 'claude-code': 'claude', 'gemini-cli': 'gemini', openai: 'codex' };

export function resolveAgents(value) {
  if (!value) return null;
  const ids = String(value).split(',').map((s) => s.trim().toLowerCase()).filter(Boolean)
    .flatMap((s) => (s === 'all' ? AGENT_IDS : [ALIASES[s] ?? s]));
  const unknown = ids.filter((i) => !ADAPTERS[i]);
  if (unknown.length) throw new Error(`Unknown agent(s): ${unknown.join(', ')}. Choose from: ${AGENT_IDS.join(', ')}, all`);
  return [...new Set(ids)];
}

function tomlString(s) {
  // TOML multi-line literal strings cannot contain '''; fall back to a basic string.
  if (!s.includes("'''")) return `'''\n${s}'''`;
  return JSON.stringify(s);
}

function tomlAgent(a) {
  return [
    `# Generated by ship-anything from agents/${a.id}.md — edit the canonical file, then re-run init.`,
    `name = ${JSON.stringify(a.id)}`,
    `description = ${JSON.stringify(a.data.description.trim())}`,
    `developer_instructions = ${tomlString(a.body.trim() + '\n')}`,
    '',
  ].join('\n');
}

